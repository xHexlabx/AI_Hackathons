"""Fallow Finn -- tier 0 of the Kaggriculture reference ladder.

Never plants anything. The reward floor.

STRATEGY
Returns PASS on every one of the 720 turns and issues no market orders, so the farm ends the season exactly as it started.

WHAT THIS TIER TEACHES
Fixes the bottom of the scale. Any agent that cannot beat Finn is losing money somewhere -- usually by buying seeds or livestock it then fails to water or feed.

Measured end-of-season bank: about 3,000 coins against the built-in
`starter` baseline over a 720-turn season.

This file is self-contained. Rename it to `main.py` and it is a valid
competition submission; or import it and call `agent(obs)` directly.

Part of the Kaggriculture Reference Agents dataset:
https://www.kaggle.com/datasets/raykkretzschmar/kaggriculture-reference-agents
Generated by scripts/build_reference_ladder.py -- edit the policy there, not here.
"""

# The only thing that differs between the six ladder agents. Every tier runs the
# identical scheduler below, so any difference in results comes from these
# numbers alone -- which is what makes the ladder useful for learning.
POLICY = {}


# ---------------------------------------------------------------------------
# Shared action scheduler -- byte-identical in all six ladder agents.
